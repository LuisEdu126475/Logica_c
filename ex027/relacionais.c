#include <stdio.h>
#include <stdlib.h>

int main(){

    // Aula 44 - Operadores Relacionais - 0 ou 1 , <, >, <=, >=, ==, !=

    printf("\t10 < 15 --> %d\n", 10 < 15);
    printf("\t10 > 15 --> %d\n", 10 > 15);
    printf("\t10 <= 15 --> %d\n", 10 <= 15);
    printf("\t10 >= 15 --> %d\n", 10 >= 15);
    printf("\t10 == 15 --> %d\n", 10 == 15);
    printf("\t10 == 10 --> %d\n", 10 == 10);
    printf("\t10 != 15 --> %d\n", 10 != 15);

    return 0;
} 